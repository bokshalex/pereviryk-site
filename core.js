// Перевірик — логіка безкоштовних інструментів. Працює в браузері, нічого не відправляє.
// Норми: Закон № 361-IX (ст. 6, 7, 8, 10, 32), Положення Мінфіну № 282 (наказ від 07.06.2024).
// Це підказка, а не юридична порада: рішення ухвалює сам суб'єкт.

/** Найближчий дедлайн річного звіту 2-фінмон: 25 січня (з 2026 року). */
export function next2FinmonDeadline(today = new Date()) {
  const y = today.getFullYear();
  const thisYear = new Date(y, 0, 25, 23, 59, 59);
  return today <= thisYear ? new Date(y, 0, 25) : new Date(y + 1, 0, 25);
}

export function daysUntil(date, today = new Date()) {
  const a = Date.UTC(today.getFullYear(), today.getMonth(), today.getDate());
  const b = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  return Math.round((b - a) / 86400000);
}

/**
 * Самоперевірка «Чи я СПФМ?».
 * a.role: 'accountant' | 'tax' | 'realtor' | 'other'
 * a.work: 'contract' (за договором з клієнтами) | 'employment' (штатний працівник)
 * a.form: 'fop' (одноосібно, ФОП/фізособа) | 'company' (юрособа)
 * a.realtorDeals: 'sale' | 'rentHigh' (оренда від 400 000 грн/міс) | 'rentLow' (лише дешевша оренда)
 * a.registered: true | false — чи вже на обліку в Держфінмоніторингу
 */
export function spfmCheck(a, today = new Date()) {
  const res = { isSpfm: false, reason: '', duties: [], deadline2fm: null, daysTo2fm: null };
  if (a.role === 'other') {
    res.reason = 'Цей інструмент — для бухгалтерів, податкових консультантів і ріелторів. Для інших професій перевір ст. 6 Закону № 361-IX окремо.';
    return res;
  }
  if (a.work === 'employment') {
    res.reason = 'Штатний працівник за трудовим договором не є суб’єктом фінмоніторингу (ст. 6 Закону № 361-IX). Обов’язки — у твого роботодавця, якщо він сам суб’єкт.';
    return res;
  }
  if (a.role === 'realtor' && a.realtorDeals === 'rentLow') {
    res.reason = 'Якщо ти працюєш лише з орендою, де плата менша за 400 000 грн на місяць, обов’язки суб’єкта не виникають (ст. 10 Закону). Щойно з’явиться купівля-продаж — виникнуть.';
    return res;
  }
  res.isSpfm = true;
  res.reason = {
    accountant: 'Бухгалтер, який надає послуги клієнтам не за трудовим договором, — спеціально визначений суб’єкт фінмоніторингу (ст. 6 Закону № 361-IX). Порогу за сумою немає.',
    tax: 'Податковий консультант, що працює з клієнтами не за трудовим договором, — спеціально визначений суб’єкт фінмоніторингу (ст. 6 Закону № 361-IX).',
    realtor: 'Посередництво або консультації під час купівлі-продажу нерухомості (або оренди від 400 000 грн/міс) роблять тебе спеціально визначеним суб’єктом (ст. 6, 10 Закону № 361-IX). Для купівлі-продажу порогу за сумою немає.',
  }[a.role];

  const d = res.duties;
  if (!a.registered) {
    d.push({ id: 'register', title: 'Стати на облік у Держфінмоніторингу', text: 'Через Е-кабінет (cabinet.fiu.gov.ua) з КЕП — не пізніше дня, коли з’явився перший клієнт. Якщо клієнти вже є — зроби це якнайшвидше.', urgent: true });
  }
  d.push({ id: 'risk', title: 'Письмовий ризик-профіль кожного клієнта', text: 'Оцінити ризик і записати, чому саме такий рівень (ст. 7). Переглядати, коли щось змінюється.' });
  d.push({ id: 'cdd', title: 'Перевірка клієнта', text: 'Ідентифікація і верифікація, кінцевий бенефіціарний власник, перевірка на PEP і в санкційних списках (ст. 8, 11).' });
  d.push({ id: 'suspicious', title: 'Повідомляти про підозрілі операції', text: 'Негайно після виникнення підозри, незалежно від суми. Про порогові операції спеціально визначені суб’єкти не повідомляють (ст. 10).' });
  d.push({ id: 'store', title: 'Зберігати документи 5 років', text: 'Не менше п’яти років після завершення співпраці з клієнтом (ст. 8).' });
  d.push({ id: '2fm', title: 'Річний звіт 2-фінмон до Мінфіну', text: 'Щороку до 25 січня через вебсистему AML з КЕП — навіть якщо клієнтів не було.' });
  if (a.form === 'company') {
    d.push({ id: 'docs', title: 'Внутрішні документи і відповідальний працівник', text: 'Правила фінмоніторингу, програма фінмоніторингу, програма навчання — затвердити до першої операції (Положення Мінфіну № 282). Призначити відповідального працівника.' });
    d.push({ id: 'training', title: 'Навчання відповідального', text: 'Протягом 3 місяців після призначення і далі не рідше ніж раз на 3 роки.' });
  } else {
    d.push({ id: 'solo', title: 'Внутрішні правила і відповідальний — не потрібні', text: 'Ти працюєш одноосібно, тож закон звільняє тебе від внутрішніх документів і відповідального працівника (ст. 8). Не плати за пакет, який тобі не потрібен.', relief: true });
  }
  res.deadline2fm = next2FinmonDeadline(today);
  res.daysTo2fm = daysUntil(res.deadline2fm, today);
  return res;
}

