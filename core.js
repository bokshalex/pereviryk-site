/** answers: { [id]: true|false } */
export function riskProfile(answers) {
  let score = 0;
  let forced = null;
  const reasons = [];
  for (const item of RISK_QUESTIONS) {
    if (!answers[item.id]) continue;
    reasons.push(item.why);
    if (item.kind === 'stop') forced = 'stop';
    else if (item.kind === 'high') { if (forced !== 'stop') forced = 'high'; }
    else score += item.kind;
  }
  let level = score >= 5 ? 'high' : score >= 2 ? 'medium' : 'low';
  if (forced === 'stop') level = 'stop';
  else if (forced === 'high') level = 'high';
  const label = { low: 'Низький', medium: 'Середній', high: 'Високий', stop: 'Неприйнятний' }[level];
  if (reasons.length === 0) reasons.push('Жодного чинника підвищеного ризику не виявлено');
  return { level, label, score, reasons, measures: MEASURES[level] };
}
